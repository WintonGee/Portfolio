// Generates lib/chatbot-sources.ts from the markdown files in data/chatbot.
// This runs at BUILD time so the /api/chatbot-sources route can import a static
// module instead of reading the filesystem at runtime (the Workers runtime has
// no filesystem at process.cwd()).
const fs = require("fs");
const path = require("path");

const chatbotDir = path.join(process.cwd(), "data", "chatbot");
const outputPath = path.join(process.cwd(), "lib", "chatbot-sources.ts");

const extractDescription = (content) => {
  const lines = content.split("\n");
  for (const line of lines) {
    if (
      line.trim() &&
      !line.startsWith("#") &&
      !line.startsWith("-") &&
      !line.startsWith("*")
    ) {
      return (
        line.trim().substring(0, 100) + (line.trim().length > 100 ? "..." : "")
      );
    }
  }
  return "No description available";
};

const extractTags = (content, category) => {
  const tags = [category];
  const contentLower = content.toLowerCase();

  if (contentLower.includes("ai") || contentLower.includes("ml"))
    tags.push("ai-ml");
  if (contentLower.includes("python")) tags.push("python");
  if (contentLower.includes("javascript") || contentLower.includes("typescript"))
    tags.push("web");
  if (contentLower.includes("contact") || contentLower.includes("email"))
    tags.push("contact");
  if (contentLower.includes("education") || contentLower.includes("university"))
    tags.push("education");
  if (contentLower.includes("work") || contentLower.includes("job"))
    tags.push("professional");

  return [...new Set(tags)];
};

const sources = [];

const readMarkdownFiles = (dir, basePath = "") => {
  if (!fs.existsSync(dir)) return;

  const items = fs.readdirSync(dir, { withFileTypes: true });

  for (const item of items) {
    const fullPath = path.join(dir, item.name);
    const relativePath = basePath ? `${basePath}/${item.name}` : item.name;

    if (item.isDirectory()) {
      readMarkdownFiles(fullPath, relativePath);
    } else if (item.isFile() && item.name.endsWith(".md")) {
      const content = fs.readFileSync(fullPath, "utf-8");
      const stats = fs.statSync(fullPath);
      const category = basePath.split("/")[0] || "personal";
      const title = item.name
        .replace(".md", "")
        .replace(/-/g, " ")
        .replace(/\b\w/g, (l) => l.toUpperCase());

      const lines = content.split("\n").length;
      const words = content.split(/\s+/).filter((w) => w.length > 0).length;

      sources.push({
        path: `data/chatbot/${relativePath}`,
        content,
        title,
        category,
        lastModified: stats.mtime.toISOString(),
        size: stats.size,
        lines,
        words,
        description: extractDescription(content),
        tags: extractTags(content, category),
      });
    }
  }
};

readMarkdownFiles(chatbotDir);

const fileContent = `// This file is auto-generated by scripts/generate-chatbot-sources.js
// Do not edit manually

export interface SourceFile {
  path: string;
  content: string;
  title: string;
  category: string;
  lastModified: string;
  size: number;
  lines: number;
  words: number;
  description: string;
  tags: string[];
}

export const CHATBOT_SOURCES: SourceFile[] = ${JSON.stringify(sources, null, 2)};
`;

fs.writeFileSync(outputPath, fileContent);
console.log(`✅ Generated ${sources.length} chatbot sources into ${outputPath}`);
